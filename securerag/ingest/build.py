"""Build corpus, chunks, saved splits and the data report from the fetched manifest.

Run:  python -m securerag.ingest.fetch_govuk   (needs network, once)
      python -m securerag.ingest.build
"""

import argparse
import json
import random
import statistics
from collections import Counter
from pathlib import Path

from securerag.config import Config
from securerag.ingest.chunk import make_chunks
from securerag.ingest.clean import clean_document
from securerag.ingest.synthetic_restricted import make_records, record_to_chunk

N_RESTRICTED = 40
QUESTION_PAGES = 200  # pages set aside as the source for the 150 clean questions (week 2)


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def write_jsonl(path: Path, rows: list[dict]) -> None:
    path.write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows), encoding="utf-8"
    )


def build(data_dir: Path, seed: int, chunk_tokens: int) -> dict:
    manifest = read_jsonl(data_dir / "manifest.jsonl")
    corpus, chunks, dropped = [], [], []
    for m in manifest:
        doc = json.loads((data_dir / "raw" / m["raw_file"]).read_text(encoding="utf-8"))
        text, problems = clean_document(doc)
        if problems:
            dropped.append({"path": m["path"], "problems": problems})
            continue
        corpus.append({**m, "text": text, "n_chars": len(text)})
        chunks.extend(make_chunks(m["path"], m["url"], m["title"], text, chunk_tokens))
    write_jsonl(data_dir / "corpus.jsonl", corpus)

    restricted = make_records(N_RESTRICTED, seed)
    write_jsonl(data_dir / "restricted.jsonl", restricted)
    chunks.extend(record_to_chunk(r) for r in restricted)
    write_jsonl(data_dir / "chunks.jsonl", chunks)

    paths = sorted(d["path"] for d in corpus)
    random.Random(seed).shuffle(paths)
    n_q = min(QUESTION_PAGES, len(paths) // 2)
    splits = {
        "seed": seed,
        "question_source": sorted(paths[:n_q]),
        "other": sorted(paths[n_q:]),
    }
    (data_dir / "splits.json").write_text(json.dumps(splits, indent=1), encoding="utf-8")
    return {"corpus": corpus, "chunks": chunks, "dropped": dropped, "splits": splits}


def make_report(result: dict, manifest_n: int) -> str:
    corpus, chunks, dropped = result["corpus"], result["chunks"], result["dropped"]
    official = [c for c in chunks if c["trust"] == "official"]
    lens = sorted(d["n_chars"] for d in corpus)
    cwords = [len(c["text"].split()) for c in official]
    schema = Counter(d["schema"] for d in corpus)
    reasons = Counter(p for d in dropped for p in d["problems"])
    top = sorted(corpus, key=lambda d: -d["n_chars"])[:3]
    dup = len(official) - len({c["text"] for c in official})
    lines = [
        "# Data report",
        "",
        "Generated by `python -m securerag.ingest.build`. Do not edit by hand.",
        "",
        "## Counts",
        f"- Pages fetched: {manifest_n}",
        f"- Pages kept: {len(corpus)}; dropped: {len(dropped)}",
        f"- Official chunks: {len(official)}; synthetic restricted chunks: "
        f"{len(chunks) - len(official)}",
        f"- Question-source pages: {len(result['splits']['question_source'])}; "
        f"other: {len(result['splits']['other'])}",
        "",
        "## Distributions",
        "",
        "Page type: " + ", ".join(f"{k} {v}" for k, v in sorted(schema.items())),
        "",
    ]
    if lens:
        p90 = lens[int(0.9 * len(lens))]
        lines += [
            f"Page length (chars): min {lens[0]}, median {int(statistics.median(lens))}, "
            f"p90 {p90}, max {lens[-1]}",
            "",
            f"Chunk length (words): min {min(cwords)}, median {int(statistics.median(cwords))}, "
            f"max {max(cwords)}",
            "",
        ]
    lines += [
        "## Quality problems found",
        "- Dropped for: " + (", ".join(f"{k} ({v})" for k, v in reasons.items()) or "nothing"),
        f"- Duplicate official chunk texts: {dup}",
        f"- Tiny chunks (<30 words): {sum(1 for w in cwords if w < 30)}",
        "- Largest pages: " + ", ".join(f"{d['path']} ({d['n_chars']} chars)" for d in top),
        "- Pages are a live snapshot; `manifest.jsonl` stores a sha256 per page to spot drift.",
        "- Pages come from topic searches, so coverage is skewed to popular services.",
        "",
        "## Sample records",
    ]
    for d in corpus[:2]:
        lines += ["", f"**{d['title']}** ({d['url']}, {d['schema']})", "", d["text"][:300] + "..."]
    r = next((c for c in chunks if c["trust"] == "restricted"), None)
    if r:
        lines += ["", f"**Synthetic restricted chunk** ({r['chunk_id']})", "", r["text"]]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", type=Path, default=Path("data"))
    ap.add_argument("--seed", type=int, default=Config().seed)
    args = ap.parse_args()
    res = build(args.data, args.seed, Config().chunk_tokens)
    n = len(read_jsonl(args.data / "manifest.jsonl"))
    Path("results/data_report.md").write_text(make_report(res, n), encoding="utf-8")
    print(f"kept {len(res['corpus'])}, chunks {len(res['chunks'])}")
